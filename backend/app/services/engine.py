import pandas as pd
import numpy as np
from app.core.config import settings
from app.core.sandbox import safe_compile_and_execute
from app.services.metrics import calculate_metrics

def run_backtest_engine(df: pd.DataFrame, alpha_code: str, alpha_type: str):
    """
    Executes the backtest using vectorized operations where possible.
    """
    # 1. Pre-compute Indicators
    df['smaShort'] = df['close'].rolling(window=20).mean().fillna(0)
    df['smaLong'] = df['close'].rolling(window=50).mean().fillna(0)
    
    # 2. Generate Signals
    if alpha_type == 'Python':
        alpha_func = safe_compile_and_execute(alpha_code, df)
        
        # Test if the function is vectorized (takes df) or row-based (takes row)
        # Try passing the whole dataframe first
        try:
            signals = alpha_func(df)
            if isinstance(signals, (pd.Series, np.ndarray, list)):
                df['signal'] = signals
            else:
                # Fallback to apply if it returned a single string for the whole df
                df['signal'] = df.apply(alpha_func, axis=1)
        except Exception:
            # Fallback to apply for row-by-row
            try:
                df['signal'] = df.apply(alpha_func, axis=1)
            except Exception as e:
                raise ValueError(f"Alpha execution failed: {e}")
    elif alpha_type == 'Math':
        df['signal'] = 'HOLD'
        df['BUY'] = False
        df['SELL'] = False
        
        try:
            # Evaluate each line sequentially
            lines = [line.strip() for line in alpha_code.split('\n') if line.strip() and not line.strip().startswith('#')]
            for line in lines:
                # Ensure the user is only assigning to variables or doing valid math
                if '=' in line:
                    df.eval(line, inplace=True)
            
            # Map BUY and SELL boolean columns to signal
            if 'BUY' in df.columns:
                df.loc[df['BUY'] == True, 'signal'] = 'BUY'
            if 'SELL' in df.columns:
                df.loc[df['SELL'] == True, 'signal'] = 'SELL'
                
        except Exception as e:
            raise ValueError(f"Math evaluation failed: {e}")
            
    if 'signal' not in df.columns:
        df['signal'] = 'HOLD'
        
    df['signal'] = df['signal'].fillna('HOLD')
    
    # 3. Vectorized Execution mechanics
    # Map signals to target positions
    df['target_position'] = np.nan
    df.loc[df['signal'] == 'BUY', 'target_position'] = 1
    df.loc[df['signal'] == 'SELL', 'target_position'] = 0
    df['position'] = df['target_position'].ffill().fillna(0)
    
    # Identify trades
    df['position_change'] = df['position'].diff().fillna(0)
    
    # Execution price includes slippage
    # If buying, we pay more. If selling, we receive less.
    df['exec_price'] = df['close']
    df.loc[df['position_change'] > 0, 'exec_price'] = df['close'] * (1 + settings.SLIPPAGE_RATE)
    df.loc[df['position_change'] < 0, 'exec_price'] = df['close'] * (1 - settings.SLIPPAGE_RATE)
    
    # Calculate costs (commission)
    df['commission_cost'] = (df['position_change'].abs() * df['exec_price']) * settings.COMMISSION_RATE
    
    # Daily PnL
    # PnL is generated by holding a position from previous close to current close
    df['price_return'] = df['close'].pct_change().fillna(0)
    
    # Account for execution slippage on trade entry day:
    # On the day a position is entered, the return from that day is from exec_price to close
    # Wait, the simplest robust way is to track cash and holdings value.
    
    initial_capital = 100000.0
    cash = initial_capital
    holdings = 0.0
    
    # While true vectorization of cash/holdings is possible, iterating over trade events
    # is often required for precise compounding if we reinvest.
    # We will use a fast compiled loop approach or a simplified vectorization.
    
    equity = np.zeros(len(df))
    cash_arr = np.zeros(len(df))
    holdings_arr = np.zeros(len(df))
    
    trades = 0
    wins = 0
    trade_entry_price = 0.0
    
    logs = []
    
    # We'll use a fast iteration for portfolio simulation
    # since we need real-time streams anyway, we can yield chunks if we wanted, 
    # but for engine.py we calculate it fast and return arrays.
    
    prices = df['close'].values
    exec_prices = df['exec_price'].values
    pos = df['position'].values
    pos_change = df['position_change'].values
    comms = df['commission_cost'].values
    signals = df['signal'].values
    
    current_cash = initial_capital
    current_holdings = 0.0
    current_shares = 0.0
    
    valid_start = 50  # Let SMAs warm up
    
    for i in range(len(df)):
        if i < valid_start:
            equity[i] = current_cash
            cash_arr[i] = current_cash
            continue
            
        action_log = None
        trade_pnl = 0.0
        
        # Execute Trade
        change = pos_change[i]
        if change > 0: # BUY
            # Buy as many shares as possible with current cash
            # For simplicity, we model allocating 100% of capital
            alloc = current_cash
            cost = comms[i]
            investable = alloc - cost
            current_shares = investable / exec_prices[i]
            current_cash -= alloc
            trade_entry_price = exec_prices[i]
            trades += 1
            action_log = f"BUY @ {exec_prices[i]:.2f}"
            
        elif change < 0: # SELL
            # Sell all shares
            proceeds = current_shares * exec_prices[i]
            cost = comms[i]
            current_cash += (proceeds - cost)
            
            trade_pnl_pct = (exec_prices[i] - trade_entry_price) / trade_entry_price
            if trade_pnl_pct > 0:
                wins += 1
            
            trade_pnl = trade_pnl_pct
            action_log = f"SELL @ {exec_prices[i]:.2f} | PnL: {(trade_pnl_pct*100):.2f}%"
            current_shares = 0.0
            
        # Update daily holdings value based on closing price
        current_holdings = current_shares * prices[i]
        current_equity = current_cash + current_holdings
        
        equity[i] = current_equity
        cash_arr[i] = current_cash
        holdings_arr[i] = current_holdings
        
        # Log entry if there was a trade, or occasionally
        if action_log or i % 10 == 0 or i == len(df) - 1:
            logs.append({
                "time": df['time'].iloc[i].strftime("%Y-%m-%d"),
                "price": float(prices[i]),
                "smaShort": float(df['smaShort'].iloc[i]),
                "smaLong": float(df['smaLong'].iloc[i]),
                "signal": str(signals[i]),
                "pnl": float(trade_pnl * 100) if action_log and "SELL" in action_log else 0.0,
                "action": action_log or "Position held"
            })
            
    df['equity'] = equity
    df['cash'] = cash_arr
    df['holdings'] = holdings_arr
    
    # Metrics
    metrics_result = calculate_metrics(
        pd.DataFrame({'time': df['time'].iloc[valid_start:], 'value': df['equity'].iloc[valid_start:]}),
        trades=trades,
        wins=wins
    )
    
    # Return processed data for streaming
    return df, logs, metrics_result
